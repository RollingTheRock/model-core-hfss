def _fmt_worst(v) -> str:
    """Format a worst-case value; None/NaN → 'N/A' (ERR-003 single-port)."""
    if v is None:
        return "N/A"
    try:
        fv = float(v)
    except (TypeError, ValueError):
        return str(v)
    if np.isnan(fv):
        return "N/A"
    return f"{fv:.3f}"


def _fmt_cell(v) -> str:
    if v is None:
        return "N/A"
    if isinstance(v, float):
        if np.isnan(v):
            return "N/A"
        return f"{v:.4f}"
    return str(v)


def _plot_single_s_params(
    freqs: np.ndarray, s11_db: np.ndarray, s21_db: np.ndarray, design_name: str, out_png: Path
) -> str:
    """Plot single-ended S11 (return loss) / S21 (insertion loss)."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams["font.sans-serif"] = ["Microsoft YaHei", "SimHei", "DejaVu Sans"]
    plt.rcParams["axes.unicode_minus"] = False
    fig, ax = plt.subplots(figsize=(8, 4.5))
    f_ghz = freqs / 1e9
    ax.plot(f_ghz, s11_db, label="S11 (回损 @端口1)", linewidth=1.8)
    ax.plot(f_ghz, s21_db, label="S21 (插损 1→2)", linewidth=1.8)
    ax.set_xlabel("Frequency (GHz)")
    ax.set_ylabel("Magnitude (dB)")
    ax.set_title(f"{design_name} — single-ended S-parameters")
    ax.grid(True, alpha=0.3)
    ax.legend(loc="best", fontsize=9)
    fig.tight_layout()
    fig.savefig(out_png, dpi=130)
    plt.close(fig)
    return out_png.as_posix()


def _plot_single_convergence(passes: list[dict], design_name: str, out_png: Path) -> str:
    """Plot adaptive pass convergence (tetrahedra + delta-S, dual axis)."""
    if not passes:
        return ""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams["font.sans-serif"] = ["Microsoft YaHei", "SimHei", "DejaVu Sans"]
    plt.rcParams["axes.unicode_minus"] = False
    fig, ax1 = plt.subplots(figsize=(8, 3.5))
    x = list(range(1, len(passes) + 1))
    tets = [p.get("tetrahedra", 0) or 0 for p in passes]
    deltas = [p.get("delta_s") for p in passes]
    ax1.bar(x, tets, color="#6BAED6", alpha=0.75, label="四面体")
    ax1.set_xlabel("自适应迭代")
    ax1.set_ylabel("四面体数", color="#2171B5")
    ax1.tick_params(axis="y", labelcolor="#2171B5")
    ax2 = ax1.twinx()
    dx = [i + 1 for i, d in enumerate(deltas) if d is not None]
    dy = [d for d in deltas if d is not None]
    if dy:
        ax2.plot(dx, dy, "o-", color="#E6550D", linewidth=2, markersize=6, label="ΔS")
        ax2.set_ylabel("ΔS", color="#E6550D")
    ax1.set_title(f"{design_name} — 网格收敛")
    ax1.grid(True, alpha=0.25, axis="y")
    fig.tight_layout()
    fig.savefig(out_png, dpi=130)
    plt.close(fig)
    return out_png.as_posix()


@dataclass
class SingleEndedReportData:
    """Structured inputs for the single-ended (2-port) report renderer.

    Deliberately separate from ``ReportData`` (the differential/mixed-mode
    pipeline). Single-ended templates (coax / microstrip) have no differential
    pair, so forcing them through ``SIMetrics``/``MixedMode`` would produce
    pseudo-differential numbers (§13.3 forbids fabricating Sdd21 from S11/S21).
    This data object carries only honest single-ended quantities: S11, S21.
    """

    task_id: str
    touchstone: Touchstone
    design_name: str
    template: str
    s11_db: np.ndarray  # return loss, port1 ref
    s21_db: np.ndarray  # insertion loss port1->port2
    worst: dict
    poi_rows: list[list[str]]  # [[freq, S11, S21], ...]
    poi_headers: list[str]
    warnings: list[str]
    convergence_passes: list[dict] | None
    model_screenshot: str | None
    acceptance_results: list[dict]
    input_hash: str


