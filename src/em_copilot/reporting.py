def _hash_file(path: str | Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()[:16]


def _fmt_freq(hz: float) -> str:
    if hz >= 1e9:
        return f"{hz / 1e9:.3f} GHz"
    if hz >= 1e6:
        return f"{hz / 1e6:.3f} MHz"
    if hz >= 1e3:
        return f"{hz / 1e3:.3f} kHz"
    return f"{hz:.3f} Hz"


@dataclass
class ReportData:
    """All structured inputs to the report renderer (§13.3: numbers from code)."""

    task: SITask
    touchstone: Touchstone
    metrics: SIMetrics
    mm: MixedMode
    acceptance_results: list[dict]
    warnings: list[str]
    input_hash: str
    compliance: ComplianceStatus
    worst: dict
    poi_snapshot: list[dict]  # points of interest
    tdr: tuple[np.ndarray, np.ndarray] | None = None
    # Optional assets from the AEDT run (added for the richer HTML report):
    model_screenshot: str | None = None  # path to model preview JPEG
    convergence_passes: list[dict] | None = None  # [{pass, tetrahedra, delta_s}]

    @property
    def pass_fail(self) -> bool:
        """Back-compat boolean view: PASS → True, anything else → False."""
        return self.compliance == ComplianceStatus.PASS


def _plot_s_params(metrics: SIMetrics, out_png: Path) -> str:
    """Plot Sdd21/Sdd11/Scd21 over frequency. Returns relative path string."""
    fig, ax = plt.subplots(figsize=(8, 4.5))
    f_ghz = metrics.freqs / 1e9
    ax.plot(f_ghz, metrics.sdd21_db, label="Sdd21 (IL)", linewidth=1.8)
    ax.plot(f_ghz, metrics.sdd11_db, label="Sdd11 (RL)", linewidth=1.5)
    ax.plot(f_ghz, metrics.scd21_db, label="Scd21 (mode conv)", linewidth=1.2, linestyle="--")
    ax.set_xlabel("Frequency (GHz)")
    ax.set_ylabel("Magnitude (dB)")
    ax.set_title(f"{metrics.pair_name}: S-parameters")
    ax.grid(True, alpha=0.3)
    ax.legend(loc="best", fontsize=9)
    fig.tight_layout()
    fig.savefig(out_png, dpi=130)
    plt.close(fig)
    return out_png.as_posix()


def _plot_tdr(t: np.ndarray, z: np.ndarray, out_png: Path) -> str:
    fig, ax = plt.subplots(figsize=(8, 3.5))
    ax.plot(t * 1e9, z, linewidth=1.5)
    ax.set_xlabel("Time (ns)")
    ax.set_ylabel("Impedance (Ω)")
    ax.set_title("TDR (step response, estimated)")
    ax.grid(True, alpha=0.3)
    fig.tight_layout()
    fig.savefig(out_png, dpi=130)
    plt.close(fig)
    return out_png.as_posix()


def _plot_convergence(passes: list[dict], out_png: Path) -> str:
    """Plot adaptive pass convergence: tetrahedra + delta-S (dual axis).

    Returns relative path string. No-op (returns "") when no pass data.
    """
    if not passes:
        return ""
    fig, ax1 = plt.subplots(figsize=(8, 3.5))
    x = list(range(1, len(passes) + 1))
    tets = [p.get("tetrahedra", 0) or 0 for p in passes]
    deltas = [p.get("delta_s") for p in passes]
    ax1.bar(x, tets, color="#6BAED6", alpha=0.75, label="Tetrahedra")
    ax1.set_xlabel("Adaptive Pass")
    ax1.set_ylabel("Tetrahedra (×1000)", color="#2171B5")
    ax1.tick_params(axis="y", labelcolor="#2171B5")
    ax2 = ax1.twinx()
    # Only plot delta-S where we have values
    dx = [i + 1 for i, d in enumerate(deltas) if d is not None]
    dy = [d for d in deltas if d is not None]
    if dy:
        ax2.plot(dx, dy, "o-", color="#E6550D", linewidth=2, markersize=6, label="ΔS")
        ax2.set_ylabel("Delta-S (convergence)", color="#E6550D")
        ax2.tick_params(axis="y", labelcolor="#E6550D")
    ax1.set_title("Mesh Convergence")
    ax1.grid(True, alpha=0.25, axis="y")
    fig.tight_layout()
    fig.savefig(out_png, dpi=130)
    plt.close(fig)
    return out_png.as_posix()


def _html_escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def _html_table(headers: list[str], rows: list[list[str]]) -> str:
    head = "".join(f"<th>{_html_escape(h)}</th>" for h in headers)
    body = []
    for row in rows:
        cells = "".join(f"<td>{_html_escape(c)}</td>" for c in row)
        body.append(f"<tr>{cells}</tr>")
    return (
        '<table class="metrics"><thead><tr>'
        f"{head}</tr></thead><tbody>"
        + "".join(body)
        + "</tbody></table>"
    )


