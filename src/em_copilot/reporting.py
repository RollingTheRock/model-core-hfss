def build_report_data(
    task: SITask,
    ts: Touchstone,
    mm: MixedMode,
    metrics: SIMetrics,
    warnings: list[str],
    *,
    model_screenshot: str | None = None,
    convergence_passes: list[dict] | None = None,
) -> ReportData:
    """Assemble the full structured report data from workflow outputs.

    The two keyword-only args carry optional AEDT-side assets gathered during
    the solve run: a model-preview JPEG and adaptive-pass convergence data.
    When absent the report simply omits those sections.
    """
    poi_snapshot = [FrequencySpec.parse(p.frequency).hz for p in task.points_of_interest]
    poi_rows = []
    for f_hz in poi_snapshot:
        row = metrics.at_frequency(f_hz)
        row["frequency"] = _fmt_freq(f_hz)
        poi_rows.append(row)

    acceptance_results = evaluate_acceptance(metrics, task.acceptance)
    # Three-state compliance (I-06 / §7). Ordering matters: an invalid rule
    # (unparseable frequency/value, missing metric, no crosstalk aggressors)
    # is a *configuration error*, not an electrical failure — it must surface as
    # ERROR before any PASS/FAIL tally, so a bad spec is never misreported as a
    # product failing its limits (ERR-004).
    if any(r.get("error") for r in acceptance_results):
        compliance = ComplianceStatus.ERROR
    elif not acceptance_results:
        compliance = ComplianceStatus.NOT_EVALUATED
    elif all(r.get("passed") for r in acceptance_results):
        compliance = ComplianceStatus.PASS
    else:
        compliance = ComplianceStatus.FAIL
    worst = worst_case(metrics)

    return ReportData(
        task=task,
        touchstone=ts,
        metrics=metrics,
        mm=mm,
        acceptance_results=acceptance_results,
        warnings=warnings,
        input_hash=_hash_file(ts.path),
        compliance=compliance,
        worst=worst,
        poi_snapshot=poi_rows,
        model_screenshot=model_screenshot,
        convergence_passes=convergence_passes,
    )
